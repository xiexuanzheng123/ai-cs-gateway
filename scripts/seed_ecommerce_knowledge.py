def fetch_existing_ids() -> set[str]:
    request = urllib.request.Request(
        f"{GATEWAY_BASE_URL}/api/customer-service/admin/knowledge",
        method="GET",
    )
    with urllib.request.urlopen(request, timeout=30) as response:
        payload = json.loads(response.read().decode("utf-8"))
    return {item["knowledge_id"] for item in payload.get("knowledge", [])}


def create_knowledge(item: tuple[str, str, str, str]) -> dict:
    knowledge_id, question, category, content = item
    body = json.dumps(
        {
            "knowledge_id": knowledge_id,
            "question": question,
            "content": content,
            "category": category,
            "owner": "seed_script",
            "version": "v1",
            "status": "published",
        },
        ensure_ascii=False,
    ).encode("utf-8")
    request = urllib.request.Request(
        f"{GATEWAY_BASE_URL}/api/customer-service/admin/knowledge",
        data=body,
        method="POST",
        headers={"Content-Type": "application/json; charset=utf-8"},
    )
    with urllib.request.urlopen(request, timeout=120) as response:
        return json.loads(response.read().decode("utf-8"))


def main() -> int:
    existing = fetch_existing_ids()
    summary = {"total": 0, "created": 0, "skipped": 0, "failed": 0, "failures": []}

    for item in SEED_ITEMS:
        summary["total"] += 1
        knowledge_id = item[0]
        if knowledge_id in existing:
            summary["skipped"] += 1
            print(f"[skip] {knowledge_id}")
            continue
        try:
            create_knowledge(item)
            summary["created"] += 1
            existing.add(knowledge_id)
            print(f"[ok] {knowledge_id} {item[1]}")
        except urllib.error.HTTPError as error:
            detail = error.read().decode("utf-8", errors="replace")
            summary["failed"] += 1
            summary["failures"].append({"knowledge_id": knowledge_id, "error": f"{error.code} {detail}"})
            print(f"[failed] {knowledge_id} {error.code} {detail}")
        except Exception as error:  # noqa: BLE001
            summary["failed"] += 1
            summary["failures"].append({"knowledge_id": knowledge_id, "error": str(error)})
            print(f"[failed] {knowledge_id} {error}")

    print(json.dumps(summary, ensure_ascii=False, indent=2))
    return 0 if summary["failed"] == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
